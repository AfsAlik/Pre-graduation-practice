def concurrency(d: Doc, r: rd.Results) -> None:
    d.h(3, "3.6.5 Одновременность выполнения группы функций")
    d.p("Ступенчатый тест выполнен с последовательным увеличением числа виртуальных пользователей "
        "до 50, 100 и 200; тест с двумя экземплярами серверного приложения – при 200 "
        "пользователях, распределенных между экземплярами поровну. Оба экземпляра работали на "
        "одной виртуальной машине стенда. Результаты по группам запросов приведены в таблице "
        "{tab:res_steps}; время по всем видам запросов при 100 пользователях приведено в таблице "
        "{tab:res_main}.")
    rows = [LOAD_HEAD]
    for users in (50, 100, 200):
        level = r.level(r.steps, users)
        minutes = f" ({num(level['minutes'], 1)} мин)" if level else ""
        for index, name in enumerate(STEP_ROWS):
            label = f"{users} польз.{minutes}" if index == 0 else ""
            rows.append(load_row(label, name, r.request(level, name)))
    two = r.level(r.two, 200)
    for index, name in enumerate(STEP_ROWS):
        label = "200 польз., два экземпляра" if index == 0 else ""
        rows.append(load_row(label, name, r.request(two, name)))
    d.table("res_steps", "Время выполнения запросов при ступенчатой нагрузке", rows, LOAD_WIDTHS, font=9,
            align="l,l,r,r,r,r,r,r")
    if r.defects:
        d.p(f"Нагрузочные тесты выявили дефекты серверной части ({len(r.defects)}), которые были "
            "устранены в ходе испытаний; сведения о них приведены в таблице {tab:res_defects}. "
            "После устранения каждого дефекта нагрузочные тесты повторялись; в таблицах "
            "{tab:res_main} и {tab:res_steps} приведены результаты последнего прогона, выполненного "
            "с одинаковыми параметрами для всех тестов. Правило расчета числа соединений с базой "
            "данных приведено в руководстве администратора (подраздел 4.1.3).")
        rows = [["№", "Тест, время", "Проявление", "Причина", "Устранение"]]
        for number, defect in enumerate(r.defects, 1):
            started = rd.local(rd.parse_dt(defect["started_at"]))
            rows.append([str(number), f"{defect['test']}, {started:%d.%m.%Y %H:%M}",
                         defect["symptom"], defect["cause"], defect["fix"]])
        d.table("res_defects", "Дефекты, выявленные нагрузочными тестами", rows,
                [0.8, 2.9, 4.3, 4.5, 4.0], font=9, align="c,l,l,l,l")
    t = (r.main or {}).get("retraining")
    if t:
        d.p(f"Во время основного теста выполнено повторное обучение модели категоризации "
            f"(обучений: {t['trainings']}, общая длительность {num(t['training_seconds_total'], 1)} с). "
            "Время выполнения основных запросов во время обучения и вне его сравнивается в таблице "
            "{tab:res_retrain}.")
        rows = [["Показатель", "Без обучения", "Во время обучения"],
                ["Число основных запросов", num(t["requests_without_training"], 0),
                 num(t["requests_during_training"], 0)],
                ["Среднее время, мс", num(t["mean_without_training_ms"], 0),
                 num(t["mean_during_training_ms"], 0)],
                ["95-й перцентиль, мс", num(t["p95_without_training_ms"], 0),
                 num(t["p95_during_training_ms"], 0)],
                ["Изменение 95-го перцентиля", "", pct(t["p95_change_percent"]) + " (допустимо не "
                 "более 10 %)"]]
        d.table("res_retrain", "Время выполнения основных запросов при повторном обучении модели",
                rows, [6.5, 4.0, 6.0], align="l,c,c")
    d.p("Оценки по пунктам методики п. 4.1.15 ПМИ приведены в таблице {tab:res_s15}.")
    d.table("res_s15", "Результаты проверки одновременности выполнения функций (этап 15)",
            item_rows([r.stage(15)], with_stage=False), ITEM_WIDTHS, font=9, align="c,l,l,l")


