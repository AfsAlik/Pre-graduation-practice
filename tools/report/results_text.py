def categorization(d: Doc, r: rd.Results) -> None:
    check = r.check(5, "в")
    model = r.model or {}
    quality = r.quality or {}
    if not check:
        return
    errors = check.get("errors", [])
    total, correct = check["total"], check["correct"]
    found = re.search(r"accuracy ([\d.]+)", check.get("detail", ""))
    model_correct = total - len(errors)
    d.p("Качество автоматической категоризации оценено на контрольной выборке из "
        f"{total} операций с эталонными категориями, которая не используется при обучении модели "
        "(подраздел 3.4.1). Операции выборки были введены через программный интерфейс без "
        "указания категории, и присвоенные системой категории сравнивались с эталонными; кроме "
        "того, аналитиком выполнена оценка активной модели на той же выборке. Показатели приведены "
        "в таблице {tab:res_ml}.")
    rows = [["Показатель", "Значение", "Требование"],
            ["Точность при вводе операций через программный интерфейс",
             f"{correct} из {total} ({pct(check['accuracy'] * 100)})",
             "не менее 80 % (п. 4.3.1.3 ТЗ)"],
            ["Доля правильных ответов модели (accuracy)",
             f"{model_correct} из {total} ({num(float(found.group(1)) if found else model.get('accuracy'), 3)})",
             "–"]]
    for key, title in (("precision", "Точность по категориям (precision), макроусреднение"),
                       ("recall", "Полнота (recall), макроусреднение"),
                       ("f1", "F1-мера, макроусреднение")):
        if model.get(key) is not None:
            rows.append([title, num(model[key], 3), "–"])
    if model.get("unseen_accuracy") is not None:
        rows.append(["Доля правильных ответов на торговых точках, отсутствующих в обучающей выборке",
                     num(model["unseen_accuracy"], 3), "не установлено"])
    if model.get("samples") is not None:
        rows.append(["Обучающих примеров активной модели (версия "
                     f"{model.get('version')})", num(model["samples"], 0), "–"])
    if quality.get("training_samples") is not None:
        rows.append(["В том числе примеров, накопленных пользователями",
                     num(quality["training_samples"], 0), "–"])
    d.table("res_ml", "Показатели качества автоматической категоризации", rows, [8.5, 3.5, 4.5],
            align="l,c,c")
    text = (f"Требование п. 4.3.1.3 ТЗ выполняется: точность при вводе операций составила "
            f"{pct(check['accuracy'] * 100)} при требуемых 80 %."
            if check["accuracy"] >= 0.8 else
            f"Требование п. 4.3.1.3 ТЗ не выполняется: точность при вводе операций составила "
            f"{pct(check['accuracy'] * 100)} при требуемых 80 %.")
    entry_errors = check.get("entry_errors", [])
    if model_correct != correct and entry_errors:
        text += (f" При вводе операций правильно определены категории {correct} операций, при "
                 f"оценке модели – {model_correct}: при вводе операции категория присваивается "
                 "только при вероятности не ниже порога 0,3 (подраздел 3.4.1), а на результат "
                 "влияют и примеры, подтвержденные самим пользователем. Операции, категория "
                 "которых при вводе определена неверно или не присвоена, приведены в таблице "
                 "{tab:res_ml_entry}, ошибки модели при ее оценке – в таблице {tab:res_ml_errors}.")
    elif model_correct != correct:
        text += (f" При вводе операций правильно определены категории {correct} операций, при "
                 f"оценке модели – {model_correct}. Ошибки модели приведены в таблице "
                 "{tab:res_ml_errors}.")
    else:
        text += " Ошибки модели приведены в таблице {tab:res_ml_errors}."
    if model.get("unseen_accuracy") is not None:
        text += (" Доля правильных ответов на торговых точках, которых модель при обучении не "
                 f"видела, значительно ниже ({num(model['unseen_accuracy'], 3)}): качество "
                 "категоризации новых наименований зависит от накопления примеров, подтвержденных "
                 "пользователями, поэтому обучающую выборку необходимо расширять в ходе опытной "
                 "эксплуатации.")
    d.p(text)
    if errors:
        rows = [["Описание операции", "Эталонная категория", "Категория, определенная моделью"]]
        rows += [[e["text"], e["expected"], e["predicted"]] for e in errors]
        d.table("res_ml_errors", "Ошибки модели на контрольной выборке", rows, [8.0, 4.0, 4.5])
    if entry_errors and model_correct != correct:
        rows = [["Описание операции", "Эталонная категория", "Категория, присвоенная при вводе"]]
        rows += [[e["text"], e["expected"], e["assigned"]] for e in entry_errors]
        d.table("res_ml_entry", "Операции контрольной выборки с неверно определенной при вводе "
                "категорией", rows, [8.0, 4.0, 4.5])


