def cell(text) -> str:
    """Текст ячейки без символов разметки."""
    text = str(text).replace("|", "/").replace("*", "").replace("\n", " ")
    return re.sub(r"\s+", " ", text).strip()


class Doc:
    def __init__(self) -> None:
        self.lines: list[str] = []

    def p(self, text: str = "") -> None:
        self.lines += [text, ""]

    def h(self, level: int, text: str) -> None:
        self.lines += ["#" * level + " " + text, ""]

    def items(self, values: list[str]) -> None:
        for index, value in enumerate(values):
            end = "." if index == len(values) - 1 else ";"
            self.lines.append(f"- {value.rstrip('.;')}{end}")
        self.lines.append("")

    def table(self, key: str, caption: str, rows: list[list], widths: list[float], font: int = 10,
              align: str | None = None) -> None:
        self.lines.append(f"!table {key} | {caption}")
        self.lines.append("!widths " + ",".join(str(w) for w in widths))
        self.lines.append(f"!font {font}")
        if align:
            self.lines.append(f"!align {align}")
        for row in rows:
            self.lines.append("| " + " | ".join(cell(c) for c in row) + " |")
        self.lines.append("")


def item_rows(stages: list[rd.Stage], with_stage: bool = True) -> list[list[str]]:
    rows = [["Пункт", "Проверка", "Результат", "Оценка"]]
    for stage in stages:
        for item in stage.items:
            label = f"{stage.number} {item.letter}" if with_stage else item.letter
            rows.append([label, item.title, item.measured, item.verdict_text])
    return rows


