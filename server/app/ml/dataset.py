_SUFFIXES = [
    "", "", "", " MOSCOW RUS", " EKATERINBURG RU", " G EKATERINBURG", " RUS", " 1234",
    " N 5512", " оплата", " покупка", " SBOL", " *4821", " SPB RU", " OOO", " ИП",
]
_PREFIXES = ["", "", "", "Оплата ", "Покупка ", "SBP ", "RETAIL ", "Списание ", "POS "]


def build_training_set(seed: int = 42, variants: int = 4) -> list[dict]:
    """Формирует обучающую выборку: исходные строки и их типичные вариации.

    Поле group содержит исходную строку: вариации одной строки при оценке
    качества не должны попадать одновременно в обучающую и отложенную части.
    """
    rng = random.Random(seed)
    samples: list[dict] = []
    for (kind, category), texts in SEED_DATA.items():
        for text in texts:
            samples.append({"text": text, "kind": kind, "category": category, "group": text})
            for _ in range(variants):
                variant = rng.choice(_PREFIXES) + text + rng.choice(_SUFFIXES)
                if rng.random() < 0.3:
                    variant = variant.upper()
                elif rng.random() < 0.3:
                    variant = variant.lower()
                samples.append(
                    {"text": variant, "kind": kind, "category": category, "group": text})
    rng.shuffle(samples)
    return samples
